"""Writes the hub as Markdown, one README.md per folder, mirroring the repo. A
local repo exports to <repo>/docs/hub/ (which the walker skips); a cloned
GitHub repo to ./output/<owner>-<repo>/.
"""

from __future__ import annotations

import os
import posixpath
import re
from pathlib import Path

from docgen.hub import ROOT, HubPlan, hub_tree, overview_status
from docgen.repos import RepoSource

EXPORT_DIR = "docs/hub"
MARKER = "<!-- Generated by docgen's hub export. Edits are overwritten on the next export. -->"


def default_export_dir(source: RepoSource) -> Path:
    if source.is_clone:
        return Path.cwd() / "output" / f"{source.owner}-{source.name}"
    return source.path / EXPORT_DIR


def slug(heading: str) -> str:
    """The anchor GitHub gives a heading: lowercase, punctuation dropped, spaces to dashes."""
    text = re.sub(r"[^\w\- ]", "", heading.strip().lower())
    return text.replace(" ", "-")


def shift_headings(md: str, top: int) -> str:
    """Move markdown headings so the highest one is at level `top`, keeping
    their relative levels. Lines inside code fences are left alone."""
    lines = md.splitlines()
    in_code = False
    levels = []
    for line in lines:
        if line.lstrip().startswith("```"):
            in_code = not in_code
        elif not in_code and (m := re.match(r"^(#{1,6})\s", line)):
            levels.append(len(m.group(1)))
    if not levels:
        return md
    delta = top - min(levels)
    out, in_code = [], False
    for line in lines:
        if line.lstrip().startswith("```"):
            in_code = not in_code
        elif not in_code and (m := re.match(r"^(#{1,6})(\s.*)$", line)):
            line = "#" * max(1, min(6, len(m.group(1)) + delta)) + m.group(2)
        out.append(line)
    return "\n".join(out)


def _split_summary(summary: str) -> tuple[str, str]:
    """Split a directory summary into (role part, how-it-fits part) so the
    contents table can go between them."""
    match = re.search(r"^#{1,6}\s+How it fits together\s*$", summary, re.M | re.I)
    if not match:
        return summary.strip(), ""
    return summary[: match.start()].strip(), summary[match.start():].strip()


def _cell(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


class _Exporter:
    def __init__(self, plan: HubPlan, hub: dict, out_dir: Path, source: RepoSource):
        self.plan = plan
        self.hub = hub
        self.out_dir = out_dir
        self.source = source
        self.status = {}
        self._collect(hub_tree(plan, hub))
        self.status[("overview", "overview")] = overview_status(plan, hub)

    def _collect(self, node: dict) -> None:
        self.status[(node["kind"], node["path"])] = node["status"]
        for child in node.get("children", []):
            self._collect(child)

    def readme_path(self, d: str) -> Path:
        return self.out_dir / d / "README.md" if d else self.out_dir / "README.md"

    def source_link(self, rel_path: str, from_dir: str) -> str:
        url = self.source.source_url(rel_path)
        if url:
            return url
        target = self.source.path / rel_path
        return Path(os.path.relpath(target, self.readme_path(from_dir).parent)).as_posix()

    def note(self, kind: str, name: str) -> str:
        """A line saying why a summary is missing or may be out of date, or ''."""
        status = self.status.get((kind, name))
        error = _cell(self.hub["errors"].get(f"{kind}:{name}", ""))[:200]
        store = {"file": self.hub["files"], "dir": self.hub["dirs"]}.get(kind)
        exists = bool(self.hub["overview"]) if kind == "overview" else name in store
        if status == "stale" or (status == "error" and exists):
            reason = f"the last attempt to update it failed ({error})" if status == "error" else (
                "the code changed after it was written")
            return f"_This summary may be out of date: {reason}._\n\n"
        if status == "error":
            return f"_No summary: the last attempt failed ({error})._\n\n"
        if status == "missing":
            return "_Not summarized yet._\n\n"
        return ""

    def contents_table(self, d: str) -> str:
        info = self.plan.dirs[d]
        rows = []
        for sub in sorted(info.subdirs):
            name = posixpath.basename(sub)
            purpose = self.hub["dirs"].get(sub, {}).get("purpose", "")
            rows.append(f"| [{name}/]({name}/README.md) | {_cell(purpose)} |")
        small = self.hub["dirs"].get(d, {}).get("small_files", {})
        for p in sorted(info.files):
            name = posixpath.basename(p)
            if self.plan.is_tiny(p):
                link = self.source_link(p, d)
                purpose = small.get(name, "")
            else:
                link = f"#{slug(name)}"
                purpose = self.hub["files"].get(p, {}).get("purpose", "")
            rows.append(f"| [{name}]({link}) | {_cell(purpose)} |")
        if not rows:
            return ""
        return "| Name | What it is |\n|---|---|\n" + "\n".join(rows)

    def dir_body(self, d: str, level: int) -> str:
        """Role, contents table, how it fits together, then the file summaries,
        with the top headings at `level`."""
        h = "#" * level
        entry = self.hub["dirs"].get(d)
        parts = [self.note("dir", d)] if self.note("dir", d) else []
        role, fits = _split_summary(entry["summary"]) if entry else ("", "")
        if role:
            parts.append(shift_headings(role, level))
        table = self.contents_table(d)
        if table:
            parts.append(f"{h} Contents\n\n{table}")
        if fits:
            parts.append(shift_headings(fits, level))

        files = [p for p in sorted(self.plan.dirs[d].files) if not self.plan.is_tiny(p)]
        if files:
            parts.append(f"{h} Files")
        for p in files:
            name = posixpath.basename(p)
            f = self.plan.files[p]
            meta = f"[Source]({self.source_link(p, d)}) · {f.language} · {f.lines} lines"
            entry = self.hub["files"].get(p)
            body = self.note("file", p) + (shift_headings(entry["summary"], level + 2) if entry else "")
            parts.append(f"{h}# {name}\n\n{meta}\n\n{body.strip()}")
        return "\n\n".join(part.strip() for part in parts if part.strip())

    def root_readme(self) -> str:
        title = self.source.github or self.source.path.name
        parts = [MARKER, f"# {title}"]
        overview = self.hub["overview"]
        if overview:
            note = self.note("overview", "overview")
            if note:
                parts.append(note.strip())
            parts.append(shift_headings(overview["summary"], 2))
            if overview.get("diagram"):
                parts.append(f"## Architecture diagram\n\n```mermaid\n{overview['diagram']}\n```")
            elif overview.get("diagram_problem"):
                parts.append(f"_The architecture diagram was left out: {overview['diagram_problem']}._")
        else:
            parts.append("_No overview yet. Build the hub to generate one._")
        parts.append("## Repository layout\n\n" + self.dir_body(ROOT, 3))
        return "\n\n".join(parts) + "\n"

    def dir_readme(self, d: str) -> str:
        parent = posixpath.dirname(d)
        up = "../README.md"
        entry = self.hub["dirs"].get(d, {})
        lines = [MARKER, f"# {d}/", f"[Up to {parent + '/' if parent else 'the overview'}]({up})"]
        if entry.get("purpose"):
            lines.append(f"_{entry['purpose']}_")
        lines.append(self.dir_body(d, 2))
        return "\n\n".join(lines) + "\n"


def export_hub(plan: HubPlan, hub: dict, out_dir: str | Path, source: RepoSource) -> list[Path]:
    """Write one README.md per folder into out_dir and return the files written.

    READMEs left over from an earlier export, for folders that no longer
    exist, are removed, but only ones that carry this exporter's marker.
    """
    out_dir = Path(out_dir)
    exporter = _Exporter(plan, hub, out_dir, source)
    written = []
    for d in sorted(plan.dirs):
        path = exporter.readme_path(d)
        path.parent.mkdir(parents=True, exist_ok=True)
        text = exporter.root_readme() if d == ROOT else exporter.dir_readme(d)
        path.write_text(text, encoding="utf-8")
        written.append(path)

    keep = set(written)
    for old in out_dir.rglob("README.md"):
        if old not in keep and old.read_text(encoding="utf-8", errors="replace").startswith(MARKER):
            old.unlink()
    return written
