"""Phase 5: apply generated docs to a repo.

Two outputs:
  * Docstrings inserted into Python source (functions, methods, classes).
  * docs/API.md built from generated endpoint docs. Endpoint functions do not
    get a docstring; their markdown reference lives in API.md only.

Editing source is the risky step, so it is done in two stages. `plan_apply`
computes every change in memory and verifies it; nothing is written until
`write_plan` is called. Verification per file:

  1. The edited text must still parse.
  2. The definition count must be unchanged, and the AST must have grown by
     exactly two nodes (Expr + Constant) per inserted docstring.
  3. Each target definition must read back the intended docstring.

If any check fails, that file is left untouched and reported. Docs are also
skipped when the code changed since generation (source hash mismatch), so a
stale description is never attached to different code.

Line endings are preserved: files are read and written as bytes, and inserted
lines use the file's own newline style.
"""

from __future__ import annotations

import ast
import difflib
import inspect
import io
import re
from dataclasses import dataclass, field
from pathlib import Path

from docgen.generator import repo_structure_hash, source_hash
from docgen.indexer import ensure_unique_ids
from docgen.models import Chunk
from docgen.parser import parse_repo

API_MARKER = "<!-- generated by docgen -->"
OVERVIEW_MARKER = "<!-- generated by docgen -->"
DEFS = (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)


@dataclass
class Skip:
    id: str
    reason: str


@dataclass
class FileChange:
    path: Path
    rel: str
    old_text: str
    new_text: str
    applied: list[str]


@dataclass
class ApiDoc:
    path: Path
    old_text: str | None
    new_text: str
    endpoints: int

    @property
    def changed(self) -> bool:
        return self.old_text != self.new_text


@dataclass
class OverviewDoc:
    path: Path
    old_text: str | None
    new_text: str

    @property
    def changed(self) -> bool:
        return self.old_text != self.new_text


@dataclass
class ApplyPlan:
    changes: list[FileChange] = field(default_factory=list)
    skipped: list[Skip] = field(default_factory=list)
    api: ApiDoc | None = None
    overview: OverviewDoc | None = None

    @property
    def docstring_count(self) -> int:
        return sum(len(c.applied) for c in self.changes)


# ---------------------------------------------------------------- docstrings


def _normalize(text: str) -> str:
    text = text.replace("\r\n", "\n").strip()
    return "\n".join(line.rstrip() for line in text.split("\n"))


def _format_docstring(text: str, indent: str, nl: str) -> list[str]:
    """Render docstring text as source lines, escaped so it reads back exactly."""
    escaped = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if escaped.endswith('"'):
        escaped = escaped[:-1] + '\\"'  # avoid a run of four quotes at the end
    lines = escaped.split("\n")
    if len(lines) == 1:
        return [f'{indent}"""{escaped}"""{nl}']
    out = [f'{indent}"""{lines[0]}{nl}']
    for line in lines[1:]:
        out.append((indent + line if line.strip() else "") + nl)
    out.append(f'{indent}"""{nl}')
    return out


def _insertion_point(node: ast.AST, lines: list[str]) -> tuple[int, str] | str:
    """Where to insert a docstring: (line index, indent), or a skip reason.

    The docstring goes directly above the first statement of the body. If that
    statement is a decorated def/class, it goes above the decorators, not
    between them and the def.
    """
    first = node.body[0]
    decorators = getattr(first, "decorator_list", [])
    first_line = min([first.lineno] + [d.lineno for d in decorators])
    line = lines[first_line - 1]
    indent = re.match(r"[ \t]*", line).group()
    if not decorators and first.col_offset != len(indent.encode("utf-8")):
        return "body starts on the same line as the definition (one-liner); not modified"
    return first_line - 1, indent


def _apply_to_file(
    path: Path, targets: list[tuple[Chunk, str]]
) -> tuple[str | None, str, list[str], list[Skip]]:
    """Return (new_text or None, old_text, applied ids, skips) for one file."""
    skips: list[Skip] = []
    try:
        raw = path.read_bytes().decode("utf-8")
        tree = ast.parse(raw)
    except (UnicodeDecodeError, SyntaxError) as e:
        reason = f"could not read/parse file ({type(e).__name__}); not modified"
        return None, "", [], [Skip(c.id, reason) for c, _ in targets]

    lines = io.StringIO(raw, newline="").readlines()  # splits only on \n, \r, \r\n
    nl = "\r\n" if "\r\n" in raw else "\n"

    old_defs = [n for n in ast.walk(tree) if isinstance(n, DEFS)]
    by_line: dict[int, int] = {}
    for i, n in enumerate(old_defs):
        by_line.setdefault(n.lineno, i)

    inserts = []  # (line index, new lines, chunk, normalized text, def index)
    for chunk, text in targets:
        i = by_line.get(chunk.start_line)
        if i is None or old_defs[i].name != chunk.name:
            skips.append(Skip(chunk.id, "could not locate the definition in the file"))
            continue
        point = _insertion_point(old_defs[i], lines)
        if isinstance(point, str):
            skips.append(Skip(chunk.id, point))
            continue
        idx, indent = point
        norm = _normalize(text)
        new_lines = _format_docstring(norm, indent, nl)
        if isinstance(old_defs[i], ast.ClassDef):
            new_lines.append(nl)  # PEP 257: blank line after a class docstring
        inserts.append((idx, new_lines, chunk, norm, i))

    if not inserts:
        return None, raw, [], skips

    # Bottom-to-top so earlier line numbers stay valid while inserting.
    for idx, new_lines, *_ in sorted(inserts, key=lambda t: t[0], reverse=True):
        lines[idx:idx] = new_lines
    new_text = "".join(lines)

    failure = _verify(tree, new_text, [(norm, i) for _, _, _, norm, i in inserts])
    if failure:
        reason = f"verification failed ({failure}); file left unchanged"
        skips.extend(Skip(c.id, reason) for _, _, c, _, _ in inserts)
        return None, raw, [], skips

    return new_text, raw, [c.id for _, _, c, _, _ in inserts], skips


def _verify(old_tree: ast.AST, new_text: str, inserted: list[tuple[str, int]]) -> str | None:
    """Return a description of what went wrong, or None if the edit checks out."""
    try:
        new_tree = ast.parse(new_text)
    except SyntaxError as e:
        return f"edited file no longer parses: {e.msg} at line {e.lineno}"

    old_defs = [n for n in ast.walk(old_tree) if isinstance(n, DEFS)]
    new_defs = [n for n in ast.walk(new_tree) if isinstance(n, DEFS)]
    if len(old_defs) != len(new_defs):
        return "definition count changed"

    grown = sum(1 for _ in ast.walk(new_tree)) - sum(1 for _ in ast.walk(old_tree))
    if grown != 2 * len(inserted):
        return f"unexpected AST change ({grown} nodes added, expected {2 * len(inserted)})"

    for norm, i in inserted:
        if ast.get_docstring(new_defs[i]) != inspect.cleandoc(norm):
            return f"docstring for {new_defs[i].name!r} did not read back correctly"
    return None


# -------------------------------------------------------------------- API.md


def _build_api_md(
    repo: Path,
    items: list[tuple[Chunk, str]],
    docs_dir: str,
    force: bool,
    plan: ApplyPlan,
) -> None:
    if not items:
        return
    path = (repo / docs_dir / "API.md").resolve()
    if repo not in path.parents:
        raise ValueError(f"docs dir {docs_dir!r} resolves outside the repo")

    items = sorted(items, key=lambda it: (it[0].route or "~", it[0].http_method or "", it[0].name))
    parts = [
        API_MARKER,
        "",
        "# API Reference",
        "",
        "_Generated by docgen from the source code. Review before publishing._",
        "",
    ]
    for chunk, text in items:
        verb = chunk.http_method or "ANY"
        heading = f"{verb} {chunk.route}" if chunk.route else f"{verb} (route not detected)"
        parts += [
            f"## {heading}",
            "",
            text.strip(),
            "",
            f"_Handler: `{chunk.name}` in `{chunk.file_path}`_",
            "",
        ]
    new_text = "\n".join(parts).rstrip("\n") + "\n"

    old_text = None
    if path.exists():
        old_text = path.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n")
        if not old_text.startswith(API_MARKER) and not force:
            plan.skipped.append(
                Skip(
                    path.relative_to(repo).as_posix(),
                    "exists and was not generated by docgen, so it was left alone",
                )
            )
            return
    plan.api = ApiDoc(path=path, old_text=old_text, new_text=new_text, endpoints=len(items))


def _build_overview_md(
    repo: Path,
    overview: dict | None,
    chunks: list,
    docs_dir: str,
    force: bool,
    plan: ApplyPlan,
) -> None:
    if not overview:
        return
    if overview.get("structure_hash") != repo_structure_hash(chunks):
        plan.skipped.append(
            Skip("overview", "repo structure changed since generation (re-run `docgen overview`)")
        )
        return

    path = (repo / docs_dir / "OVERVIEW.md").resolve()
    if repo not in path.parents:
        raise ValueError(f"docs dir {docs_dir!r} resolves outside the repo")

    new_text = OVERVIEW_MARKER + "\n\n# Project Overview\n\n" + overview["text"].strip() + "\n"
    old_text = None
    if path.exists():
        old_text = path.read_bytes().decode("utf-8", errors="replace").replace("\r\n", "\n")
        if not old_text.startswith(OVERVIEW_MARKER) and not force:
            plan.skipped.append(
                Skip(
                    path.relative_to(repo).as_posix(),
                    "exists and was not generated by docgen, so it was left alone",
                )
            )
            return
    plan.overview = OverviewDoc(path=path, old_text=old_text, new_text=new_text)


# ----------------------------------------------------------------- top level


def plan_apply(
    repo_path: str | Path,
    generated: dict,
    docs_dir: str = "docs",
    include_api_md: bool = True,
    include_overview: bool = True,
    force: bool = False,
) -> ApplyPlan:
    """Work out every change without writing anything."""
    repo = Path(repo_path).resolve()
    chunks = parse_repo(repo)
    ensure_unique_ids(chunks)
    by_id = {c.id: c for c in chunks}
    plan = ApplyPlan()

    per_file: dict[str, list[tuple[Chunk, str]]] = {}
    endpoints: list[tuple[Chunk, str]] = []

    for id_, item in generated.get("items", {}).items():
        chunk = by_id.get(id_)
        if chunk is None:
            plan.skipped.append(Skip(id_, "no longer exists in the repo"))
            continue
        kind = item.get("kind")
        if kind == "docstring" and chunk.docstring:
            plan.skipped.append(Skip(id_, "already has a docstring"))
            continue
        if item.get("source_hash") != source_hash(chunk):
            plan.skipped.append(Skip(id_, "code changed since generation (re-run `generate`)"))
            continue
        if kind == "docstring":
            per_file.setdefault(chunk.file_path, []).append((chunk, item["text"]))
        elif kind == "endpoint_doc":
            endpoints.append((chunk, item["text"]))
        else:
            plan.skipped.append(Skip(id_, f"unknown kind {kind!r}"))

    for rel in sorted(per_file):
        new_text, old_text, applied, skips = _apply_to_file(repo / rel, per_file[rel])
        plan.skipped.extend(skips)
        if new_text is not None:
            plan.changes.append(FileChange(repo / rel, rel, old_text, new_text, applied))

    if include_api_md:
        _build_api_md(repo, endpoints, docs_dir, force, plan)
    if include_overview:
        _build_overview_md(repo, generated.get("overview"), chunks, docs_dir, force, plan)
    return plan


def write_plan(plan: ApplyPlan) -> None:
    """Write a verified plan to disk."""
    for change in plan.changes:
        change.path.write_bytes(change.new_text.encode("utf-8"))
    if plan.api and plan.api.changed:
        plan.api.path.parent.mkdir(parents=True, exist_ok=True)
        plan.api.path.write_text(plan.api.new_text, encoding="utf-8")
    if plan.overview and plan.overview.changed:
        plan.overview.path.parent.mkdir(parents=True, exist_ok=True)
        plan.overview.path.write_text(plan.overview.new_text, encoding="utf-8")


def diff_lines(change: FileChange) -> list[str]:
    """Unified diff for display (line endings stripped)."""
    return list(
        difflib.unified_diff(
            change.old_text.splitlines(),
            change.new_text.splitlines(),
            fromfile=f"a/{change.rel}",
            tofile=f"b/{change.rel}",
            lineterm="",
        )
    )
